#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql into supabase/APPLY_ALL_MIGRATIONS.sql
 * for one-shot paste in Supabase SQL Editor. Run: npm run supabase:bundle
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migDir = join(root, "supabase", "migrations");
const outPath = join(root, "supabase", "APPLY_ALL_MIGRATIONS.sql");

const files = readdirSync(migDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = files.map((f) => {
  const body = readFileSync(join(migDir, f), "utf8").trim();
  return `-- ========== ${f} ==========\n\n${body}\n`;
});

const header = `-- Fabric Flo — run entire file in Supabase SQL Editor (new project)
-- Generated by npm run supabase:bundle — ${files.length} migrations
-- After this: configure Auth URLs and deploy the web app with VITE_* env vars (see docs/BACKEND_SETUP.md)

-- Defer function-body validation so migrations can define functions before the
-- tables they reference (e.g. is_production_member before production_members).
-- Safe: the function bodies still run correctly once all tables exist.
set check_function_bodies = off;

`;

writeFileSync(outPath, header + parts.join("\n"), "utf8");
console.log(`Wrote ${outPath} (${files.length} files)`);
