#!/usr/bin/env node
/**
 * Builds a non-destructive Claude knowledge pack from repo sources.
 *   docs/export/Fabric_Flo_Knowledge_Pack.md
 *   docs/export/Fabric_Flo_Knowledge_Pack.pdf (best effort, needs Chrome / puppeteer)
 *
 * Reads only docs and source files; never touches Supabase or app behavior.
 * Run: npm run knowledge:export
 */
import { accessSync, constants, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "docs", "export");
const outMd = join(outDir, "Fabric_Flo_Knowledge_Pack.md");
const outPdf = join(outDir, "Fabric_Flo_Knowledge_Pack.pdf");

function read(relPath) {
  return readFileSync(join(root, relPath), "utf8").trim();
}

/** Pull `create table ... public.NAME (` identifiers from a migration for a compact schema list. */
function tableNames(relPath) {
  const sql = read(relPath);
  const names = [];
  const re = /create table if not exists public\.(\w+)/gi;
  let m;
  while ((m = re.exec(sql)) !== null) names.push(m[1]);
  return names;
}

const sections = [
  { title: "Glossary and language contract", body: read("docs/FABRIC_FLO_GLOSSARY.md") },
  {
    title: "Domain types (src/types.ts)",
    body: "```ts\n" + read("src/types.ts") + "\n```",
  },
  { title: "Backend API (Supabase RPCs)", body: read("docs/BACKEND_API.md") },
  { title: "Sync and conflict model", body: read("docs/SYNC.md") },
  { title: "Backend setup (operator checklist)", body: read("docs/BACKEND_SETUP.md") },
  {
    title: "Database tables (from migration 002)",
    body:
      "Normalized schema tables:\n\n" +
      tableNames("supabase/migrations/002_productions_normalized_rls.sql")
        .map((n) => `- \`${n}\``)
        .join("\n"),
  },
];

const header = `# Fabric Flo — Claude knowledge pack

Generated by \`npm run knowledge:export\` on ${new Date().toISOString().slice(0, 10)}.
Source of truth for Fabric Flo's product language, user flows, and Supabase backend.

Contains no secrets, credentials, or user data. Safe to upload to a Claude.ai Project or share
with partners. To refresh, edit the source docs (starting with \`docs/FABRIC_FLO_GLOSSARY.md\`) and
re-run the command.

---
`;

const md =
  header +
  "\n" +
  sections.map((s) => `## ${s.title}\n\n${s.body}`).join("\n\n---\n\n") +
  "\n";

mkdirSync(outDir, { recursive: true });
writeFileSync(outMd, md, "utf8");
console.log(`Wrote ${outMd}`);

function chromeExecutable() {
  if (process.env.PUPPETEER_EXECUTABLE_PATH) return process.env.PUPPETEER_EXECUTABLE_PATH;
  if (process.platform === "darwin") {
    const mac = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
    try {
      accessSync(mac, constants.X_OK);
      return mac;
    } catch {
      /* fall back to puppeteer default */
    }
  }
  return undefined;
}

async function buildPdf() {
  const chrome = chromeExecutable();
  const launchOptions = chrome ? { executablePath: chrome } : {};
  const { mdToPdf } = await import("md-to-pdf");
  const css = `
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif; font-size: 11pt; line-height: 1.45; color: #111; max-width: 7.5in; margin: 0 auto; padding: 0.5in; }
    h1 { font-size: 20pt; border-bottom: 2px solid #0f172a; padding-bottom: 0.2em; }
    h2 { font-size: 14pt; margin-top: 1.2em; color: #0f172a; page-break-after: avoid; }
    table { border-collapse: collapse; width: 100%; margin: 0.6em 0; font-size: 10pt; }
    th, td { border: 1px solid #ccc; padding: 6px 8px; text-align: left; vertical-align: top; }
    th { background: #f1f5f9; }
    code, pre { font-size: 9pt; background: #f1f5f9; padding: 1px 4px; border-radius: 3px; }
    pre { padding: 8px; white-space: pre-wrap; }
    ul { padding-left: 1.2em; }
    li { margin: 0.2em 0; }
    hr { border: none; border-top: 1px solid #ddd; margin: 1.5em 0; }
    strong { color: #0f172a; }
  `;
  const pdf = await mdToPdf(
    { content: md },
    {
      dest: outPdf,
      launch_options: launchOptions,
      pdf_options: {
        format: "Letter",
        margin: { top: "0.75in", bottom: "0.75in", left: "0.75in", right: "0.75in" },
        printBackground: true,
      },
      css,
    }
  );
  if (!pdf?.filename) throw new Error("PDF generation returned no file");
  console.log(`Wrote ${outPdf}`);
}

buildPdf().catch((e) => {
  console.warn(`PDF skipped (${e?.message ?? e}). Markdown pack is ready at ${outMd}.`);
});
